-- Склад деловых остатков производства: учёт, ячейки хранения, списание, журнал «кто, когда, что».
-- Выполнить один раз в Supabase → SQL Editor (можно повторно). После migration_workplaces.sql.
--
-- Кто что может:
--   владелец производства, начальник (all) и сотрудник с полномочием «Склад остатков» (perms.stock) — вносить, править,
--     вписывать ячейку, перерезать, списывать, удалять;
--   остальные сотрудники производства — только смотреть (где лежит остаток, история);
--   клиенты — позже, при раскрое, если производство включит «Показывать остатки клиентам».
-- Все изменения — только через функции ниже: каждая пишет запись в журнал remnant_events (его нельзя править).

alter table public.productions add column if not exists stock_settings jsonb not null default '{}'::jsonb;
  -- { clients: false — показывать остатки клиентам, reasonRequired: false — требовать причину при перерезке и списании }

create table if not exists public.remnants (
  id bigint generated by default as identity primary key,       -- номер остатка (на бирке и в QR)
  production_id uuid not null references public.productions(id) on delete cascade,
  length numeric not null,
  width numeric not null,
  qty integer not null default 1,
  material text not null default '',
  thickness numeric,
  cell text,                                                       -- ячейка хранения; пусто — «ячейка не указана»
  note text,
  status text not null default 'free',                             -- free | reserved | used
  reserved_order uuid references public.orders(id) on delete set null,
  used_kind text,                                                  -- order | defect | claim | other
  used_at timestamptz,
  label_at timestamptz,                                            -- когда выпущена бирка (null — не выпущена или устарела)
  source text not null default 'manual',                           -- manual | nesting
  source_key text,                                                 -- откуда пришёл из раскроя (чтобы не было дублей)
  created_by uuid default auth.uid(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists remnants_prod on public.remnants (production_id, status);
create unique index if not exists remnants_source_key on public.remnants (production_id, source_key) where source_key is not null;

create table if not exists public.remnant_events (
  id bigint generated by default as identity primary key,
  remnant_id bigint,                                               -- без внешнего ключа: запись остаётся и после удаления остатка
  production_id uuid not null references public.productions(id) on delete cascade,
  user_id uuid default auth.uid(),
  user_name text,                                                  -- кто сделал (имя на момент действия)
  action text not null,                                            -- create | edit | cell | recut | writeoff | restore | label | delete
  before jsonb,
  after jsonb,
  qty integer,
  reason text,
  at timestamptz not null default now()
);
create index if not exists remnant_events_rem on public.remnant_events (remnant_id, at);
create index if not exists remnant_events_prod on public.remnant_events (production_id, at desc);

alter table public.remnants enable row level security;
alter table public.remnant_events enable row level security;

-- ── права ──
-- 'edit' — может менять склад; 'view' — только смотреть; null — нет доступа
create or replace function public.stock_access(p_prod uuid) returns text
language sql security definer set search_path = public stable as $$
  select case
    when p_prod is null or auth.uid() is null then null
    when exists (select 1 from productions where id = p_prod and owner_id = auth.uid() and status = 'approved') then 'edit'
    when member_can(p_prod, 'stock') then 'edit'
    when member_can(p_prod, null) then 'view'
    when is_admin() then 'view'
    else null end
$$;

drop policy if exists "remnants: склад производства" on public.remnants;
create policy "remnants: склад производства" on public.remnants for select to authenticated using (public.stock_access(production_id) is not null);
drop policy if exists "remnant_events: склад производства" on public.remnant_events;
create policy "remnant_events: склад производства" on public.remnant_events for select to authenticated using (public.stock_access(production_id) is not null);

-- запись в журнал
create or replace function public.stock_log(p_rem bigint, p_prod uuid, p_action text, p_before jsonb, p_after jsonb, p_qty integer, p_reason text) returns void
language plpgsql security definer set search_path = public as $$
declare nm text;
begin
  select coalesce(nullif(trim(m.name), ''), nullif(trim(pr.full_name), ''), pr.phone, '') into nm
    from (select auth.uid() as uid) u
    left join production_members m on m.production_id = p_prod and m.user_id = u.uid
    left join profiles pr on pr.id = u.uid;
  insert into remnant_events (remnant_id, production_id, user_name, action, before, after, qty, reason)
    values (p_rem, p_prod, nm, p_action, p_before, p_after, p_qty, nullif(trim(coalesce(p_reason, '')), ''));
end $$;

-- остаток для изменения: есть ли право
create or replace function public.stock_row_for_edit(p_id bigint) returns public.remnants
language plpgsql security definer set search_path = public as $$
declare r remnants;
begin
  select * into r from remnants where id = p_id for update;
  if not found then raise exception 'stock: not found'; end if;
  if coalesce(stock_access(r.production_id), '') <> 'edit' then raise exception 'not allowed'; end if;
  return r;
end $$;

-- причина обязательна, если так решило производство
create or replace function public.stock_need_reason(p_prod uuid, p_reason text) returns void
language plpgsql security definer set search_path = public stable as $$
begin
  if coalesce((select (stock_settings ->> 'reasonRequired')::boolean from productions where id = p_prod), false)
     and coalesce(trim(p_reason), '') = '' then raise exception 'stock: reason required'; end if;
end $$;

create or replace function public.stock_snap(r public.remnants) returns jsonb
language sql immutable as $$
  select jsonb_build_object('length', r.length, 'width', r.width, 'qty', r.qty, 'material', r.material, 'thickness', r.thickness,
    'cell', r.cell, 'note', r.note, 'status', r.status)
$$;

-- ── внести остатки списком: [{ length, width, qty, material, thickness, cell, note }] ──
create or replace function public.stock_add(p_prod uuid, p_rows jsonb) returns json
language plpgsql security definer set search_path = public as $$
declare x jsonb; r remnants; ids bigint[] := '{}'; k text;
begin
  if coalesce(stock_access(p_prod), '') <> 'edit' then raise exception 'not allowed'; end if;
  for x in select * from jsonb_array_elements(coalesce(p_rows, '[]'::jsonb)) loop
    if coalesce((x ->> 'length')::numeric, 0) <= 0 or coalesce((x ->> 'width')::numeric, 0) <= 0 then continue; end if;
    -- остаток с бирки (код бирки): уже внесён — второй раз не вносится, возвращается его номер
    k := nullif(trim(coalesce(x ->> 'source_key', '')), '');
    if k is not null then
      select * into r from remnants where production_id = p_prod and source_key = k;
      if found then ids := ids || r.id; continue; end if;
    end if;
    insert into remnants (production_id, length, width, qty, material, thickness, cell, note, source, source_key)
      values (p_prod, (x ->> 'length')::numeric, (x ->> 'width')::numeric, greatest(1, coalesce((x ->> 'qty')::integer, 1)),
              coalesce(trim(x ->> 'material'), ''), nullif(x ->> 'thickness', '')::numeric,
              nullif(trim(coalesce(x ->> 'cell', '')), ''), nullif(trim(coalesce(x ->> 'note', '')), ''),
              coalesce(nullif(x ->> 'source', ''), 'manual'), k)
      returning * into r;
    perform stock_log(r.id, p_prod, 'create', null, stock_snap(r) || jsonb_build_object('source', r.source), r.qty, null);
    ids := ids || r.id;
  end loop;
  return to_json(ids);
end $$;

-- ── поправить поля (опечатка при вводе): длина, ширина, кол-во, материал, толщина, ячейка, примечание ──
create or replace function public.stock_edit(p_id bigint, p_patch jsonb, p_reason text default null) returns void
language plpgsql security definer set search_path = public as $$
declare r remnants; n remnants; b jsonb := '{}'; a jsonb := '{}'; k text;
begin
  r := stock_row_for_edit(p_id);
  n := r;
  if p_patch ? 'length' then n.length := (p_patch ->> 'length')::numeric; end if;
  if p_patch ? 'width' then n.width := (p_patch ->> 'width')::numeric; end if;
  if p_patch ? 'qty' then n.qty := greatest(1, (p_patch ->> 'qty')::integer); end if;
  if p_patch ? 'material' then n.material := coalesce(trim(p_patch ->> 'material'), ''); end if;
  if p_patch ? 'thickness' then n.thickness := nullif(p_patch ->> 'thickness', '')::numeric; end if;
  if p_patch ? 'cell' then n.cell := nullif(trim(coalesce(p_patch ->> 'cell', '')), ''); end if;
  if p_patch ? 'note' then n.note := nullif(trim(coalesce(p_patch ->> 'note', '')), ''); end if;
  if coalesce(n.length, 0) <= 0 or coalesce(n.width, 0) <= 0 then raise exception 'stock: bad size'; end if;
  for k in select unnest(array['length', 'width', 'qty', 'material', 'thickness', 'cell', 'note']) loop
    if (stock_snap(r) -> k) is distinct from (stock_snap(n) -> k) then
      b := b || jsonb_build_object(k, stock_snap(r) -> k); a := a || jsonb_build_object(k, stock_snap(n) -> k);
    end if;
  end loop;
  if a = '{}'::jsonb then return; end if;
  update remnants set length = n.length, width = n.width, qty = n.qty, material = n.material, thickness = n.thickness, cell = n.cell, note = n.note,
    label_at = case when n.length <> r.length or n.width <> r.width or n.material <> r.material then null else label_at end,
    updated_at = now() where id = p_id;
  perform stock_log(p_id, r.production_id, case when a ?& array['cell'] and (select count(*) from jsonb_object_keys(a)) = 1 then 'cell' else 'edit' end, b, a, null, p_reason);
end $$;

-- ── вписать / сменить ячейку ──
create or replace function public.stock_cell(p_id bigint, p_cell text) returns void
language plpgsql security definer set search_path = public as $$
begin
  perform stock_edit(p_id, jsonb_build_object('cell', coalesce(p_cell, '')), null);
end $$;

-- ── перерезать: от остатка отрезали кусок, он стал меньше. Из нескольких одинаковых перерезается один (отделяется своей строкой) ──
create or replace function public.stock_recut(p_id bigint, p_length numeric, p_width numeric, p_reason text) returns bigint
language plpgsql security definer set search_path = public as $$
declare r remnants; n remnants;
begin
  r := stock_row_for_edit(p_id);
  if r.status <> 'free' then raise exception 'stock: not free'; end if;
  if coalesce(p_length, 0) <= 0 or coalesce(p_width, 0) <= 0 then raise exception 'stock: bad size'; end if;
  perform stock_need_reason(r.production_id, p_reason);
  if r.qty > 1 then
    update remnants set qty = qty - 1, updated_at = now() where id = p_id;
    insert into remnants (production_id, length, width, qty, material, thickness, cell, note, source, created_by)
      values (r.production_id, p_length, p_width, 1, r.material, r.thickness, r.cell, r.note, r.source, auth.uid()) returning * into n;
    perform stock_log(p_id, r.production_id, 'recut', jsonb_build_object('qty', r.qty), jsonb_build_object('qty', r.qty - 1, 'to', n.id), 1, p_reason);
    perform stock_log(n.id, r.production_id, 'recut', jsonb_build_object('length', r.length, 'width', r.width, 'from', p_id), jsonb_build_object('length', p_length, 'width', p_width), 1, p_reason);
    return n.id;
  end if;
  update remnants set length = p_length, width = p_width, label_at = null, updated_at = now() where id = p_id;
  perform stock_log(p_id, r.production_id, 'recut', jsonb_build_object('length', r.length, 'width', r.width), jsonb_build_object('length', p_length, 'width', p_width), 1, p_reason);
  return p_id;
end $$;

-- ── списать: в заказ, брак, рекламация, прочее. Часть из нескольких одинаковых — отделяется списанной строкой ──
create or replace function public.stock_writeoff(p_id bigint, p_qty integer, p_kind text, p_reason text) returns bigint
language plpgsql security definer set search_path = public as $$
declare r remnants; n remnants; q integer;
begin
  r := stock_row_for_edit(p_id);
  if r.status = 'used' then raise exception 'stock: already used'; end if;
  if coalesce(p_kind, '') not in ('order', 'defect', 'claim', 'other') then raise exception 'stock: bad kind'; end if;
  perform stock_need_reason(r.production_id, p_reason);
  q := least(greatest(1, coalesce(p_qty, r.qty)), r.qty);
  if q < r.qty then
    update remnants set qty = qty - q, updated_at = now() where id = p_id;
    insert into remnants (production_id, length, width, qty, material, thickness, cell, note, status, used_kind, used_at, label_at, source, created_by)
      values (r.production_id, r.length, r.width, q, r.material, r.thickness, r.cell, r.note, 'used', p_kind, now(), r.label_at, r.source, auth.uid()) returning * into n;
    perform stock_log(p_id, r.production_id, 'writeoff', jsonb_build_object('qty', r.qty), jsonb_build_object('qty', r.qty - q, 'kind', p_kind, 'to', n.id), q, p_reason);
    perform stock_log(n.id, r.production_id, 'writeoff', jsonb_build_object('from', p_id), jsonb_build_object('kind', p_kind), q, p_reason);
    return n.id;
  end if;
  update remnants set status = 'used', used_kind = p_kind, used_at = now(), reserved_order = null, updated_at = now() where id = p_id;
  perform stock_log(p_id, r.production_id, 'writeoff', jsonb_build_object('status', r.status), jsonb_build_object('status', 'used', 'kind', p_kind), r.qty, p_reason);
  return p_id;
end $$;

-- ── вернуть списанный на склад (списали по ошибке) ──
create or replace function public.stock_restore(p_id bigint, p_reason text default null) returns void
language plpgsql security definer set search_path = public as $$
declare r remnants;
begin
  r := stock_row_for_edit(p_id);
  if r.status = 'free' then return; end if;
  update remnants set status = 'free', used_kind = null, used_at = null, reserved_order = null, updated_at = now() where id = p_id;
  perform stock_log(p_id, r.production_id, 'restore', jsonb_build_object('status', r.status, 'kind', r.used_kind), jsonb_build_object('status', 'free'), r.qty, p_reason);
end $$;

-- ── удалить насовсем (ошибочная строка). Запись «кто и когда удалил» остаётся в журнале ──
create or replace function public.stock_delete(p_id bigint, p_reason text default null) returns void
language plpgsql security definer set search_path = public as $$
declare r remnants;
begin
  r := stock_row_for_edit(p_id);
  perform stock_log(p_id, r.production_id, 'delete', stock_snap(r), null, r.qty, p_reason);
  delete from remnants where id = p_id;
end $$;

-- ── бирка выпущена (этап «Бирки склада») ──
create or replace function public.stock_labeled(p_ids bigint[]) returns void
language plpgsql security definer set search_path = public as $$
declare r remnants;
begin
  for r in select * from remnants where id = any(p_ids) loop
    if coalesce(stock_access(r.production_id), '') <> 'edit' then raise exception 'not allowed'; end if;
    update remnants set label_at = now() where id = r.id;
    perform stock_log(r.id, r.production_id, 'label', null, null, r.qty, null);
  end loop;
end $$;

-- ── настройки склада: владелец или начальник производства ──
create or replace function public.stock_settings_set(p_prod uuid, p_settings jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
declare v jsonb;
begin
  if not is_my_production(p_prod) then raise exception 'not allowed'; end if;
  update productions set stock_settings = coalesce(stock_settings, '{}'::jsonb) || coalesce(p_settings, '{}'::jsonb) where id = p_prod
    returning stock_settings into v;
  return v;
end $$;

-- склад для страницы: права, настройки, название производства
create or replace function public.stock_info(p_prod uuid) returns json
language plpgsql security definer set search_path = public stable as $$
declare a text := stock_access(p_prod);
begin
  if a is null then raise exception 'not allowed'; end if;
  return (select json_build_object('access', a, 'settings', coalesce(p.stock_settings, '{}'::jsonb), 'name', p.name,
    'owner', p.owner_id = auth.uid() or is_my_production(p_prod)) from productions p where p.id = p_prod);
end $$;

