const SAY_FIX = [
  [/G-код/g, 'джи-код'], [/QR-код/g, 'кью-ар код'], [/PDF/g, 'пэ-дэ-эф'], [/PRO100/g, 'про сто'], [/Excel/g, 'Эксель'],
  [/ХДФ/g, 'ха-дэ-эф'], [/ЧПУ/g, 'чэ-пэ-у'],
]
/** текст для синтезатора: без кавычек и многоточий (на них голос спотыкается), с ударениями в спорных словах */
export function speechText(text, l) {
  let s = String(text || '').replace(/[«»"“”„]/g, '').replace(/…/g, ',').replace(/\s—\s/g, ', ').replace(/,\s*,/g, ',').replace(/^,\s*/, '')
  if (l !== 'ru') return s
  for (const [re, to] of SAY_FIX) s = s.replace(re, to)
  return s.replace(/[А-Яа-яЁё]+/g, w => {
    const low = w.toLowerCase(), v = STRESS[low]
    if (!v || v === low) return w
    return w[0] !== low[0] ? v[0].toUpperCase() + v.slice(1) : v
  })
}
